#!/usr/bin/env bash
# demo.sh — End-to-end testnet demo for the SafeWallet policy contract.
#
# This script has NOT been run against a live testnet in this repository.
# Run it yourself with:
#   ./scripts/demo.sh
# and record the output in docs/testnet-run.md when done.
#
# The script exercises the full policy lifecycle on Stellar Testnet:
#
#   Step 0a  Configure Stellar CLI for the target network
#   Step 0b  Generate and fund four throwaway testnet keys
#   Step 1   Build the WASM (wasm32v1-none target)
#   Step 2   Deploy the SafeWallet contract
#   Step 3   Resolve the native token's contract address
#   Step 4   Initialize with a 50 XLM daily cap and a recovery key
#   Step 5   Fund the wallet contract (transfer 100 XLM to it via the token contract)
#   Step 6   Verify wallet balance is at least 55 XLM (enough for the demo)
#   Step 7   Add a whitelisted recipient
#   Step 8   Transfer 10 XLM — must succeed (10 spent, 40 remaining in cap)
#   Step 9   Attempt 45 XLM + 1 stroop — must fail with DailyCapExceeded (error 2)
#            Cap arithmetic: 10_000_000_0 spent + 450_000_001 = 550_000_001 > 500_000_000 cap
#   Step 10  Freeze the wallet with the recovery key — must succeed
#   Step 11  Assert is_frozen == true
#   Step 12  Attempt transfer while frozen — must fail with WalletFrozen (error 4)
#   Step 13  Rotate the recovery key (requires BOTH owner + current recovery key)
#            Real multi-party signing: build → sign owner auth → sign recovery auth → send
#   Step 14  Attempt unfreeze with the OLD (revoked) recovery key — must fail
#            with Unauthorized (error 1)
#   Step 15  Unfreeze with the NEW recovery key — must succeed
#   Step 16  Assert is_frozen == false
#   Step 17  Transfer 5 XLM — must succeed (cap still has 40 XLM left in this window)
#   Summary  Print per-step table with transaction hashes
#
# Prerequisites:
#   - Stellar CLI v22+, installed with:
#       curl -fsSL https://github.com/stellar/stellar-cli/raw/main/install.sh | sh
#   - Rust 1.88.0 with wasm32v1-none target — rust-toolchain.toml pins this
#       automatically; or run:
#       rustup toolchain install 1.88.0
#       rustup target add wasm32v1-none --toolchain 1.88.0
#   - Internet access (testnet RPC + friendbot)
#   - Keys generated by this script are throwaway testnet accounts — never use
#     them on mainnet.
#
# Usage:
#   ./scripts/demo.sh [--network NETWORK]
#
# NETWORK defaults to "testnet". For a custom network supply --network NAME and
# export RPC_URL and PASSPHRASE environment variables before running.

set -euo pipefail

# ─── Config ──────────────────────────────────────────────────────────────────
NETWORK="${NETWORK:-testnet}"
RPC_URL="${RPC_URL:-https://soroban-testnet.stellar.org}"
PASSPHRASE="${PASSPHRASE:-Test SDF Network ; September 2015}"

OWNER_KEY="demo-owner"
RECOVERY_KEY="demo-recovery"
RECIPIENT_KEY="demo-recipient"
NEW_RECOVERY_KEY="demo-recovery-v2"

# 50 XLM daily cap in stroops (1 XLM = 10_000_000 stroops)
DAILY_CAP_STROOPS="500000000"

# Step 8: transfer 10 XLM (100_000_000 stroops)
VALID_TRANSFER_AMOUNT="100000000"

# Step 9: attempt 45 XLM + 1 stroop after already spending 10 XLM.
# Total would be 100_000_000 + 450_000_001 = 550_000_001 stroops > 500_000_000 cap.
EXCEEDING_AMOUNT="450000001"

# Step 17: transfer 5 XLM (50_000_000 stroops); 10 XLM was spent in step 8,
# 40 XLM remains — 5 XLM is within the remaining cap.
FINAL_TRANSFER_AMOUNT="50000000"

# 100 XLM to fund the wallet contract (1_000_000_000 stroops)
FUND_AMOUNT="1000000000"

WASM="target/wasm32v1-none/release/safe_wallet.wasm"

# ─── Argument parsing ─────────────────────────────────────────────────────────
while [[ $# -gt 0 ]]; do
  case "$1" in
    --network)      NETWORK="$2"; shift 2 ;;
    --network=*)    NETWORK="${1#*=}"; shift ;;
    -h|--help)
      echo "Usage: $0 [--network NETWORK]"
      exit 0
      ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done

# ─── Summary table ────────────────────────────────────────────────────────────
# Accumulate rows; printed at the end.
declare -a SUMMARY_ROWS=()

record() {
  # record <step> <expected> <result> <txhash>
  local step="$1" expected="$2" result="$3" txhash="${4:--}"
  SUMMARY_ROWS+=("$(printf '%-6s | %-36s | %-8s | %s' "$step" "$expected" "$result" "$txhash")")
}

# ─── Helpers ─────────────────────────────────────────────────────────────────
step() { printf '\n━━━ Step %s: %s ━━━\n' "$1" "$2"; }
ok()   { printf '  ✅ %s\n' "$*"; }
fail() { printf '  ❌ %s\n' "$*" >&2; }
info() { printf '  ℹ  %s\n' "$*"; }

# expect_ok <step_label> <expected_description> <command...>
# Runs the command. If it fails, prints the full output and exits 1.
# Returns the captured stdout for further inspection.
expect_ok() {
  local label="$1" description="$2"
  shift 2
  local output
  if ! output=$("$@" 2>&1); then
    fail "Step $label FAILED — expected: $description"
    fail "Command: $*"
    fail "Output:"
    printf '%s\n' "$output" >&2
    exit 1
  fi
  printf '%s\n' "$output"
}

# expect_error <step_label> <error_name> <error_code> <command...>
# Runs the command. Fails the script if:
#   - the command SUCCEEDS (exit 0), or
#   - the command fails but its output does not contain the expected error.
expect_error() {
  local label="$1" error_name="$2" error_code="$3"
  shift 3
  local output
  if output=$("$@" 2>&1); then
    fail "Step $label FAILED — command succeeded but expected error $error_name (code $error_code)"
    fail "Command: $*"
    fail "Output:"
    printf '%s\n' "$output" >&2
    exit 1
  fi
  # Command failed — verify it failed with the right error.
  if ! printf '%s\n' "$output" | grep -qE "$error_name|Error\($error_code\)|#$error_code"; then
    fail "Step $label FAILED — command failed but NOT with $error_name (code $error_code)"
    fail "Command: $*"
    fail "Actual output:"
    printf '%s\n' "$output" >&2
    exit 1
  fi
  printf '%s\n' "$output"
}

# assert_eq <step_label> <label> <expected> <actual>
assert_eq() {
  local step_label="$1" name="$2" expected="$3" actual="$4"
  if [[ "$actual" != "$expected" ]]; then
    fail "Step $step_label assertion FAILED: $name"
    fail "  expected: $expected"
    fail "  actual:   $actual"
    exit 1
  fi
  ok "$name == $expected"
}

# extract_txhash <output>
# Pulls the transaction hash (64-char hex or base64 contract IDs) from CLI output.
extract_txhash() {
  printf '%s\n' "$1" | grep -oE '[0-9a-fA-F]{64}' | head -1 || printf '%s\n' "$1" | grep -oE 'txhash[=: ]+[0-9a-fA-F]+' | head -1 || echo "-"
}

# invoke_ok <step_label> <description> <source_key> <function> [args...]
# Calls the wallet contract and fails hard if the call fails.
invoke_ok() {
  local label="$1" description="$2" source_key="$3"
  shift 3
  local output
  output=$(expect_ok "$label" "$description" \
    stellar contract invoke \
      --id "$CONTRACT_ID" \
      --source "$source_key" \
      --network "$NETWORK" \
      -- "$@")
  printf '%s\n' "$output"
}

# invoke_err <step_label> <error_name> <error_code> <source_key> <function> [args...]
# Calls the wallet contract and fails hard unless the call fails with the named error.
invoke_err() {
  local label="$1" error_name="$2" error_code="$3" source_key="$4"
  shift 4
  local output
  output=$(expect_error "$label" "$error_name" "$error_code" \
    stellar contract invoke \
      --id "$CONTRACT_ID" \
      --source "$source_key" \
      --network "$NETWORK" \
      -- "$@")
  printf '%s\n' "$output"
}

# ─── Step 0a: Configure network ──────────────────────────────────────────────
step "0a" "Configure Stellar CLI for $NETWORK"

# Add the network, treating "already exists" as success.
if stellar network add "$NETWORK" \
    --rpc-url "$RPC_URL" \
    --network-passphrase "$PASSPHRASE" 2>&1; then
  ok "Network '$NETWORK' added"
else
  # stellar network add exits non-zero if the network already exists; check.
  if stellar network ls 2>/dev/null | grep -q "^$NETWORK\b"; then
    ok "Network '$NETWORK' already configured"
  else
    fail "Failed to configure network '$NETWORK'"
    exit 1
  fi
fi

# ─── Step 0b: Generate and fund keys ─────────────────────────────────────────
step "0b" "Generate and fund throwaway testnet keys"

for KEY in "$OWNER_KEY" "$RECOVERY_KEY" "$RECIPIENT_KEY" "$NEW_RECOVERY_KEY"; do
  if ! stellar keys address "$KEY" >/dev/null 2>&1; then
    info "Generating key: $KEY"
    stellar keys generate "$KEY" --network "$NETWORK"
  else
    info "Key already exists: $KEY"
  fi
  info "Funding $KEY via friendbot"
  if ! stellar keys fund "$KEY" --network "$NETWORK" 2>&1; then
    info "Fund request failed or already funded — continuing"
  fi
done

OWNER_ADDR=$(stellar keys address "$OWNER_KEY")
RECOVERY_ADDR=$(stellar keys address "$RECOVERY_KEY")
RECIPIENT_ADDR=$(stellar keys address "$RECIPIENT_KEY")
NEW_RECOVERY_ADDR=$(stellar keys address "$NEW_RECOVERY_KEY")

info "Owner address:        $OWNER_ADDR"
info "Recovery address:     $RECOVERY_ADDR"
info "Recipient address:    $RECIPIENT_ADDR"
info "New recovery address: $NEW_RECOVERY_ADDR"

# ─── Step 1: Build ───────────────────────────────────────────────────────────
step "1" "Build safe-wallet contract (wasm32v1-none)"
cargo build --release --target wasm32v1-none \
  --manifest-path contracts/safe-wallet/Cargo.toml 2>&1 | tail -5
if [[ ! -f "$WASM" ]]; then
  fail "WASM artifact not found: $WASM"
  exit 1
fi
ok "Build complete: $WASM"

# ─── Step 2: Deploy ──────────────────────────────────────────────────────────
step "2" "Deploy SafeWallet contract"
DEPLOY_OUT=$(expect_ok "2" "contract deploy" \
  stellar contract deploy \
    --wasm "$WASM" \
    --source "$OWNER_KEY" \
    --network "$NETWORK")
CONTRACT_ID=$(printf '%s\n' "$DEPLOY_OUT" | grep -oE 'C[A-Z2-7]{55}' | head -1)
if [[ -z "$CONTRACT_ID" ]]; then
  fail "Could not extract contract ID from deploy output"
  printf '%s\n' "$DEPLOY_OUT" >&2
  exit 1
fi
ok "Deployed SafeWallet: $CONTRACT_ID"
DEPLOY_HASH=$(extract_txhash "$DEPLOY_OUT")
record "2" "deploy succeeds" "OK" "$DEPLOY_HASH"

# ─── Step 3: Resolve native token address ────────────────────────────────────
step "3" "Resolve native (XLM) token contract address"
NATIVE_TOKEN_ID=$(expect_ok "3" "contract id asset" \
  stellar contract id asset \
    --asset native \
    --network "$NETWORK")
NATIVE_TOKEN_ID=$(printf '%s\n' "$NATIVE_TOKEN_ID" | tr -d '[:space:]')
if [[ -z "$NATIVE_TOKEN_ID" ]]; then
  fail "Could not resolve native token contract address"
  exit 1
fi
ok "Native token contract: $NATIVE_TOKEN_ID"
record "3" "native token resolved" "OK" "-"

# ─── Step 4: Initialize ──────────────────────────────────────────────────────
step "4" "Initialize wallet (50 XLM cap, recovery key set, token = native SAC)"
INIT_OUT=$(invoke_ok "4" "initialize" "$OWNER_KEY" \
  initialize \
    --owner "$OWNER_ADDR" \
    --daily_cap "$DAILY_CAP_STROOPS" \
    --recovery_key "$RECOVERY_ADDR" \
    --token "$NATIVE_TOKEN_ID")
ok "Wallet initialized"
INIT_HASH=$(extract_txhash "$INIT_OUT")
record "4" "initialize succeeds" "OK" "$INIT_HASH"
info "Daily cap: $DAILY_CAP_STROOPS stroops (50 XLM)"
info "Recovery key: $RECOVERY_ADDR"
info "Token: $NATIVE_TOKEN_ID"

# ─── Step 5: Fund the wallet contract ────────────────────────────────────────
step "5" "Fund wallet contract with 100 XLM via native token contract"
FUND_OUT=$(expect_ok "5" "token transfer to wallet contract" \
  stellar contract invoke \
    --id "$NATIVE_TOKEN_ID" \
    --source "$OWNER_KEY" \
    --network "$NETWORK" \
    -- transfer \
      --from "$OWNER_ADDR" \
      --to "$CONTRACT_ID" \
      --amount "$FUND_AMOUNT")
ok "Funded wallet with 100 XLM"
FUND_HASH=$(extract_txhash "$FUND_OUT")
record "5" "fund contract succeeds" "OK" "$FUND_HASH"

# ─── Step 6: Verify wallet balance ───────────────────────────────────────────
step "6" "Verify wallet contract balance >= 55 XLM (enough for demo)"
BALANCE_OUT=$(expect_ok "6" "token balance check" \
  stellar contract invoke \
    --id "$NATIVE_TOKEN_ID" \
    --source "$OWNER_KEY" \
    --network "$NETWORK" \
    --send no \
    -- balance \
      --id "$CONTRACT_ID")
WALLET_BALANCE=$(printf '%s\n' "$BALANCE_OUT" | grep -oE '[0-9]+' | head -1)
info "Wallet balance: $WALLET_BALANCE stroops"
# 55 XLM = 550_000_000 stroops (need 10 + 5 for transfers, rest proves cap enforcement)
if [[ "$WALLET_BALANCE" -lt 550000000 ]]; then
  fail "Wallet balance ($WALLET_BALANCE stroops) is below the 550_000_000 needed for the demo"
  exit 1
fi
ok "Balance sufficient: $WALLET_BALANCE stroops (>= 550000000)"
record "6" "balance >= 55 XLM" "OK" "-"

# ─── Step 7: Add whitelisted recipient ───────────────────────────────────────
step "7" "Add recipient to whitelist"
WL_OUT=$(invoke_ok "7" "add_whitelist" "$OWNER_KEY" \
  add_whitelist \
    --address "$RECIPIENT_ADDR")
ok "Recipient whitelisted: $RECIPIENT_ADDR"
WL_HASH=$(extract_txhash "$WL_OUT")
record "7" "add_whitelist succeeds" "OK" "$WL_HASH"

# ─── Step 8: Valid transfer ───────────────────────────────────────────────────
step "8" "Transfer 10 XLM — must succeed (10 spent, 40 XLM remaining in cap)"
XFER1_OUT=$(invoke_ok "8" "transfer 10 XLM succeeds" "$OWNER_KEY" \
  transfer \
    --to "$RECIPIENT_ADDR" \
    --amount "$VALID_TRANSFER_AMOUNT")
ok "Transfer succeeded (10 XLM sent)"
XFER1_HASH=$(extract_txhash "$XFER1_OUT")
record "8" "transfer 10 XLM succeeds" "OK" "$XFER1_HASH"

# Verify via getter: spent_today should now be 100_000_000
SPENT_OUT=$(expect_ok "8-verify" "get_spent_today" \
  stellar contract invoke \
    --id "$CONTRACT_ID" \
    --source "$OWNER_KEY" \
    --network "$NETWORK" \
    --send no \
    -- get_spent_today)
SPENT_TODAY=$(printf '%s\n' "$SPENT_OUT" | grep -oE '[0-9]+' | head -1)
assert_eq "8-verify" "spent_today" "100000000" "$SPENT_TODAY"
info "spent_today confirmed: $SPENT_TODAY stroops (10 XLM)"

# ─── Step 9: Exceed daily cap ────────────────────────────────────────────────
step "9" "Transfer 45 XLM + 1 stroop — must fail with DailyCapExceeded (error 2)"
info "Cap arithmetic: 100_000_000 (spent) + 450_000_001 = 550_000_001 > 500_000_000 cap"
XCAP_OUT=$(invoke_err "9" "DailyCapExceeded" "2" "$OWNER_KEY" \
  transfer \
    --to "$RECIPIENT_ADDR" \
    --amount "$EXCEEDING_AMOUNT")
ok "Correctly rejected with DailyCapExceeded"
XCAP_HASH=$(extract_txhash "$XCAP_OUT")
record "9" "DailyCapExceeded (error 2)" "OK" "$XCAP_HASH"

# ─── Step 10: Freeze wallet ───────────────────────────────────────────────────
step "10" "Freeze wallet with recovery key"
FREEZE_OUT=$(invoke_ok "10" "freeze" "$RECOVERY_KEY" \
  freeze \
    --caller "$RECOVERY_ADDR")
ok "Wallet frozen"
FREEZE_HASH=$(extract_txhash "$FREEZE_OUT")
record "10" "freeze succeeds" "OK" "$FREEZE_HASH"

# ─── Step 11: Assert is_frozen == true ────────────────────────────────────────
step "11" "Assert is_frozen == true"
FROZEN_OUT=$(expect_ok "11" "is_frozen" \
  stellar contract invoke \
    --id "$CONTRACT_ID" \
    --source "$OWNER_KEY" \
    --network "$NETWORK" \
    --send no \
    -- is_frozen)
IS_FROZEN=$(printf '%s\n' "$FROZEN_OUT" | tr -d '[:space:]"')
assert_eq "11" "is_frozen" "true" "$IS_FROZEN"
record "11" "is_frozen == true" "OK" "-"

# ─── Step 12: Transfer while frozen ──────────────────────────────────────────
step "12" "Transfer while frozen — must fail with WalletFrozen (error 4)"
FROZ_OUT=$(invoke_err "12" "WalletFrozen" "4" "$OWNER_KEY" \
  transfer \
    --to "$RECIPIENT_ADDR" \
    --amount "10000000")
ok "Correctly rejected with WalletFrozen"
FROZ_HASH=$(extract_txhash "$FROZ_OUT")
record "12" "WalletFrozen (error 4)" "OK" "$FROZ_HASH"

# ─── Step 13: Rotate recovery key (real multi-party signing) ─────────────────
step "13" "Rotate recovery key — owner + current recovery key both sign"
#
# update_recovery_key requires two require_auth calls: the owner's (root auth,
# covered by --source) and the current recovery key's (non-root auth entry).
#
# Approach supported by stellar-cli v22+:
#   1. Build the transaction without sending (--build-only). The source account
#      (owner) signs the transaction envelope. --auto-sign covers non-root auth
#      entries recorded during simulation for the source account only; the
#      recovery key's auth entry is NOT signed yet.
#   2. Pipe the XDR through `stellar tx sign --sign-with-key RECOVERY_KEY
#      --auto-sign` to append the recovery key's signature to the auth entries.
#   3. Send the fully-signed XDR with `stellar tx send`.
#
# Note: stellar-cli --auto-sign on `contract invoke` signs auth entries for the
# source key when they are non-root. For a second signer's auth entry, we need
# a separate `stellar tx sign` pass.
ROTATE_XDR=$(expect_ok "13" "build update_recovery_key tx" \
  stellar contract invoke \
    --id "$CONTRACT_ID" \
    --source "$OWNER_KEY" \
    --network "$NETWORK" \
    --build-only \
    -- update_recovery_key \
      --new_key "$NEW_RECOVERY_ADDR")
info "Built transaction XDR (owner signed)"

# Sign the recovery key's non-root auth entry.
ROTATE_XDR_SIGNED=$(printf '%s\n' "$ROTATE_XDR" | \
  stellar tx sign \
    --sign-with-key "$RECOVERY_KEY" \
    --network "$NETWORK" \
    --auto-sign)
info "Recovery key auth signed"

# Send the fully-signed transaction.
ROTATE_OUT=$(printf '%s\n' "$ROTATE_XDR_SIGNED" | \
  expect_ok "13" "send update_recovery_key tx" \
    stellar tx send \
      --network "$NETWORK")
ok "Recovery key rotated to: $NEW_RECOVERY_ADDR"
ROTATE_HASH=$(extract_txhash "$ROTATE_OUT")
record "13" "key rotation (dual-auth)" "OK" "$ROTATE_HASH"

# ─── Step 14: Old recovery key cannot unfreeze ───────────────────────────────
step "14" "Unfreeze with OLD recovery key — must fail with Unauthorized (error 1)"
OLD_UF_OUT=$(invoke_err "14" "Unauthorized" "1" "$RECOVERY_KEY" \
  unfreeze \
    --caller "$RECOVERY_ADDR")
ok "Correctly rejected old recovery key with Unauthorized"
OLD_UF_HASH=$(extract_txhash "$OLD_UF_OUT")
record "14" "Unauthorized (error 1)" "OK" "$OLD_UF_HASH"

# ─── Step 15: New recovery key unfreezes ─────────────────────────────────────
step "15" "Unfreeze with new recovery key — must succeed"
UF_OUT=$(invoke_ok "15" "unfreeze" "$NEW_RECOVERY_KEY" \
  unfreeze \
    --caller "$NEW_RECOVERY_ADDR")
ok "Wallet unfrozen"
UF_HASH=$(extract_txhash "$UF_OUT")
record "15" "unfreeze (new key) succeeds" "OK" "$UF_HASH"

# ─── Step 16: Assert is_frozen == false ──────────────────────────────────────
step "16" "Assert is_frozen == false"
FROZEN2_OUT=$(expect_ok "16" "is_frozen after unfreeze" \
  stellar contract invoke \
    --id "$CONTRACT_ID" \
    --source "$OWNER_KEY" \
    --network "$NETWORK" \
    --send no \
    -- is_frozen)
IS_FROZEN2=$(printf '%s\n' "$FROZEN2_OUT" | tr -d '[:space:]"')
assert_eq "16" "is_frozen" "false" "$IS_FROZEN2"
record "16" "is_frozen == false" "OK" "-"

# ─── Step 17: Final transfer ──────────────────────────────────────────────────
step "17" "Transfer 5 XLM after unfreeze — must succeed"
# 10 XLM was spent in step 8; 40 XLM remain. 5 XLM is within cap.
XFER2_OUT=$(invoke_ok "17" "transfer 5 XLM post-unfreeze" "$OWNER_KEY" \
  transfer \
    --to "$RECIPIENT_ADDR" \
    --amount "$FINAL_TRANSFER_AMOUNT")
ok "Transfer succeeded (5 XLM sent)"
XFER2_HASH=$(extract_txhash "$XFER2_OUT")
record "17" "transfer 5 XLM succeeds" "OK" "$XFER2_HASH"

# ─── Summary ─────────────────────────────────────────────────────────────────
printf '\n'
printf '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n'
printf ' Demo complete\n'
printf '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n'
printf '\n'
printf 'Contract ID:    %s\n' "$CONTRACT_ID"
printf 'Network:        %s\n' "$NETWORK"
printf 'Owner:          %s\n' "$OWNER_ADDR"
printf 'Recovery (new): %s\n' "$NEW_RECOVERY_ADDR"
printf 'Recipient:      %s\n' "$RECIPIENT_ADDR"
printf 'Native token:   %s\n' "$NATIVE_TOKEN_ID"
printf '\n'
printf '%-6s | %-36s | %-8s | %s\n' "Step" "Expected" "Result" "Tx hash"
printf '%-6s-+-%-36s-+-%-8s-+-%s\n' "------" "------------------------------------" "--------" "----------------------------------------------------------------"
for row in "${SUMMARY_ROWS[@]}"; do
  printf '%s\n' "$row"
done
printf '\n'
printf 'All assertions passed.\n'
